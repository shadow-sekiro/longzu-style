/**
 * 风格维度标签：从精华池中提炼出的"气质"维度，而非具体片段。
 * 注入模型时只给维度名（如「冷峻白描」「克制短句」），不把原文贴进 prompt，
 * 避免模型把"示例里出现过的词（樱花/泡面/粉笔）"当成该用的固定素材。
 */
export const STYLE_DIMENSIONS = [
  '冷峻白描', '克制短句', '非常规比喻', '衰小孩自嘲', 'mundane 日常落地',
  '命运尺度反差', '感官细节密集', '留白不煽情', '第一人称独白', '又丧又燃',
];

/**
 * 随机抽取 k 个风格维度（不重复），作为"本次风格指令"注入 prompt。
 * 每次生成的风格侧重都不同，进一步打散模板。
 */
export function getStyleDimensions(k = 3): string[] {
  const pool = [...STYLE_DIMENSIONS];
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, Math.min(k, pool.length));
}

/**
 * 精华池仅作为"气质示范"随机抽 1 段（不固定、不写死到 prompt 结构里），
 * 用于给模型一个正版江南原著的语气锚点；抽不到则返回空。
 */

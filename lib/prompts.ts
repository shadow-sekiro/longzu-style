/**
 * 拼接用户输入的指令。
 * 关键设计（2026-08-16 修正"偏离原意"结构性 bug）：
 *  - anchors：从用户输入抽取的真实语义锚点（地点/人物/时间/事件/物件），作为**首要硬约束**，
 *    模型必须围绕它写，禁止自创无关场景；
 *  - card：本次随机生成的"笔法参考卡"（仅手法/质感养分，不是要写的内容）；
 *  - dimensions：本次随机抽取的风格维度（每次侧重不同）；
 *  - essenceSample：随机 1 段正版原著气质示范（可选，不固定）。
 * 指令层级：用户输入语义锚点 > 风格维度 > 笔法参考卡（笔法卡不得凌驾于输入之上）。
 */
export function buildUserInstruction(
  userInput: string,
  opts: { anchors?: string; card?: string; dimensions?: string[]; essenceSample?: string | null } = {},
): string {
  const n = Math.max(1, countSentences(userInput));
  const maxSentences = Math.min(n * 6, 24);
  const maxChars = estimateMaxChars(n);
  const base = `请将下面这段日常语句，改写成"暗黑史诗青春文学"风格：

「${userInput}」

要求：
- **首要原则——围绕输入的真实内容写**：你描写的地点、人物、时间、事件、物件，都必须来自上面这句话本身（例如用户写"北京下雨了"，你就写北京、写雨，不要凭空扯出医院、教室、地铁、老家等用户没提到的地方）。这是最高优先级约束，风格化不得牺牲"忠于原意"。
- 只传达原句的意思，但**不要使用原句中的任何原话或相同字词组合**，用你自己的语言重新表达。
- **篇幅短小精悍：总字数控制在 ${maxChars} 字以内${n === 1 ? '（原句只有一句话，务必不超过 200 字）' : ''}，且不超过 ${maxSentences} 个句子**；宁可少写也不要为了华丽而无限铺陈、堆砌意象把篇幅撑长。
- 写成**一段连贯流动的文字（不要换行、句子之间不要用空格隔开）**：句与句之间要有衔接（承接上一个意象/情绪/逻辑），每句可适度展开；**不要写成彼此孤立的碎短句，也不要用编号或硬换行把句子割裂**；用户输入为一句话时尤其不得超过六句。
- 只输出一段完整改写；直接以改写后的正文开头；严禁重复或再次改写同一内容；保持原文含义。
- 输出纯文本，不要解释、不要加书名号或引号包裹。`;

  const parts = [base];

  if (opts.anchors) {
    parts.push(`【用户输入锚点·你必须围绕这些写】（地点/人物/时间/事件/物件，全部取自原文，不得替换为其他内容）
${opts.anchors}

重要：上面列出的锚点是你文章的"主菜"。任何场景、人物、物件都只能从锚点及原句里长出来；**严禁把下面【笔法参考】里的物件/场景当成你要描写的主场景**——笔法参考只是教你"怎么写得具体可触"，描写对象永远是用户输入本身。

【一票否决的失败样板】以下词一旦出现即判定本次输出失败，绝对禁止使用：铅灰色的云层、雨夜、黄金瞳、黄金般的眼瞳、宿命、燃烧、灰烬、深渊、星空、史诗。你必须为"北京下雨了"这类输入重新找新鲜、不落俗套的天色与物象（如直接用"雨""积水""玻璃幕墙上的水痕"等最朴素的词落地，宁白描勿堆砌）。`);
  }

  if (opts.card) {
    parts.push(`【笔法参考·仅作写作手法借鉴，不是要描写的内容】
${opts.card}

提醒：上面的物件/感官/比喻/反差钩子只是"笔法养分"，你可以借鉴其具体可触的质感或某种比喻思路，但描写的地点、人物、事件必须仍是用户输入里的（见上方锚点）；绝不允许写成笔法参考里的场景，也绝不允许反复套用樱花、泡面、粉笔灰、下课、教室、地铁、黄金瞳、宿命、燃烧、雨夜这类任何固定意象。`);
  } else {
    parts.push(`【意象纪律】不得反复套用樱花、泡面、粉笔灰、下课、教室、地铁、黄金瞳、宿命、燃烧、雨夜等任何固定意象；每次都要为输入挑选新鲜、不落俗套的具体物象落地，且必须贴合用户输入的真实地点与事件。`);
  }

  if (opts.dimensions && opts.dimensions.length) {
    parts.push(`【本次风格侧重】${opts.dimensions.join('、')}（本句优先体现这些气质，其余维度适度兼顾即可，但不得凌驾于"忠于输入原意"之上）`);
  }

  if (opts.essenceSample) {
    parts.push(`【气质示范·正版原著片段】（仅模仿其语气与节奏，不得整段照抄、不得搬运其中任何具体意象）
${opts.essenceSample}`);
  }

  return parts.join('\n\n');
}

